  static int _leapMonth(int y) => _lunarInfo[y - 1900] & 0xf;

  static int _leapDays(int y) {
    if (_leapMonth(y) == 0) return 0;
    return (_lunarInfo[y - 1900] & 0x10000) != 0 ? 30 : 29;
  }

  static int _monthDays(int y, int m) =>
      (_lunarInfo[y - 1900] & (0x10000 >> m)) != 0 ? 30 : 29;

  static int _yearDays(int y) {
    int sum = 348;
    for (int i = 0x8000; i > 0x8; i >>= 1) {
      sum += (_lunarInfo[y - 1900] & i) != 0 ? 1 : 0;
    }
    return sum + _leapDays(y);
  }

  /// 公历日期 -> 农历字符串，形如「农历 丙午年(马年)六月十五」。
  static String toLunarDate(DateTime date) {
    final offset0 =
        DateTime(date.year, date.month, date.day).difference(DateTime(1900, 1, 31)).inDays;

    int offset = offset0;
    int temp = 0;
    int lunarYear = 1900;
    for (lunarYear = 1900; lunarYear < 2100 && offset > 0; lunarYear++) {
      temp = _yearDays(lunarYear);
      offset -= temp;
    }
    if (offset < 0) {
      offset += temp;
      lunarYear--;
    }

    final leap = _leapMonth(lunarYear);
    bool isLeap = false;
    int lunarMonth = 1;
    for (lunarMonth = 1; lunarMonth <= 12 && offset > 0; lunarMonth++) {
      if (leap > 0 && lunarMonth == leap + 1 && !isLeap) {
        lunarMonth--;
        isLeap = true;
        temp = _leapDays(lunarYear);
      } else {
        temp = _monthDays(lunarYear, lunarMonth);
      }
      offset -= temp;
      if (lunarMonth == leap + 1 && isLeap) {
        isLeap = false;
      }
    }
    if (offset == 0 && leap > 0 && lunarMonth == leap + 1) {
      if (isLeap) {
        isLeap = false;
      } else {
        isLeap = true;
        lunarMonth--;
      }
    }
    if (offset < 0) {
      offset += temp;
      lunarMonth--;
    }
    final lunarDay = offset + 1;

    return _toFullString(lunarYear, lunarMonth, lunarDay, isLeap);
  }

  static String _toFullString(int y, int m, int d, bool isLeap) {
    const gan = ['甲', '乙', '丙', '丁', '戊', '己', '庚', '辛', '壬', '癸'];
    const zhi = ['子', '丑', '寅', '卯', '辰', '巳', '午', '未', '申', '酉', '戌', '亥'];
    const sx = ['鼠', '牛', '虎', '兔', '龙', '蛇', '马', '羊', '猴', '鸡', '狗', '猪'];
    const monthNames = [
      '正', '二', '三', '四', '五', '六', '七', '八', '九', '十', '冬', '腊'
    ];
    const dayTens = ['初', '十', '廿', '三十'];
    const dayOnes = ['', '一', '二', '三', '四', '五', '六', '七', '八', '九', '十'];

    final idx = (y - 4) % 60;
    final yearStr = '${gan[idx % 10]}${zhi[idx % 12]}年(${sx[idx % 12]}年)';

    final monthStr = isLeap ? '闰${monthNames[m - 1]}月' : '${monthNames[m - 1]}月';

    String dayStr;
    if (d == 10) {
      dayStr = '初十';
    } else if (d == 20) {
      dayStr = '二十';
    } else if (d == 30) {
      dayStr = '三十';
    } else {
      final ten = d ~/ 10;
      final one = d % 10;
      dayStr = (ten == 0 ? '初' : dayTens[ten]) + (one == 0 ? '' : dayOnes[one]);
    }

    return '农历 $yearStr$monthStr$dayStr';
  }
